// Generates patches/INDEX.md: which patches touch which game file (and which
// pak assets). Needs only patch.json files, not vanilla/ or the pak key.
'use strict';
const fs = require('fs');
const path = require('path');
const { PATCHES_DIR, loadPatches } = require('./patchfmt');

const INDEX_FILE = path.join(PATCHES_DIR, 'INDEX.md');
const code = (s) => '`' + s + '`';
const link = (p) => (fs.existsSync(path.join(p.dir, 'README.md')) ? `[${p.id}](${p.id}/README.md)` : p.id);
const cell = (s) => String(s).replace(/\|/g, '\\|');

function renderIndex(patches = loadPatches()) {
    const byTarget = new Map();
    for (const p of patches) {
        for (const t of p.targets) {
            if (!byTarget.has(t.target)) byTarget.set(t.target, []);
            byTarget.get(t.target).push({ p, t });
        }
    }
    const out = [
        '# Patch index',
        '',
        'Generated by `npm run patches:index` (also run by `npm run patches:build`). Do not edit by hand.',
        '',
        '## By patch',
        '',
        '| Patch | Status | Files | Title |',
        '|---|---|---|---|',
    ];
    for (const p of patches) {
        out.push(`| ${link(p)} | ${p.status} | ${p.targets.map((t) => code(path.posix.basename(t.target))).join(', ')} | ${cell(p.title || '')} |`);
    }
    out.push('', '## By file', '');
    for (const target of [...byTarget.keys()].sort()) {
        const parts = byTarget.get(target);
        out.push(`### ${code(target)}`, '');
        const pak = parts.some(({ t }) => t.assets);
        if (!pak) {
            out.push('| Patch | Status | Edits | Offsets |', '|---|---|---|---|');
            for (const { p, t } of parts) {
                const offs = t.edits.map((e) => e.offset);
                out.push(`| ${link(p)} | ${p.status} | ${t.edits.length} | ${offs.slice(0, 6).join(', ')}${offs.length > 6 ? ', …' : ''} |`);
            }
            // Claims in the build-added sections (scripts/lib/pe.js), so parallel
            // work can see which RVAs are taken.
            const claims = [];
            for (const { p, t } of parts) {
                if (!t.section) continue;
                const rng = (rva, size) => `${rva}..0x${(Number(rva) + Number(size)).toString(16).toUpperCase()}`;
                for (const c of t.section.code || []) claims.push([Number(c.rva), `| ${link(p)} | ${p.status} | code | ${code(rng(c.rva, c.size))} |`]);
                for (const d of t.section.data || []) claims.push([Number(d.rva), `| ${link(p)} | ${p.status} | data | ${code(rng(d.rva, d.size))} |`]);
                const u = (t.section.unwind || []).length;
                if (u) claims.push([Infinity, `| ${link(p)} | ${p.status} | unwind | ${u} entr${u === 1 ? 'y' : 'ies'} |`]);
            }
            if (claims.length) {
                out.push('', 'Added sections (RVA ranges claimed in `.fspcode` / `.fspdata`):', '', '| Patch | Status | Kind | RVA range |', '|---|---|---|---|');
                for (const [, row] of claims.sort((a, b) => a[0] - b[0])) out.push(row);
            }
        } else {
            // One row per asset, so overlapping work on the same asset is visible.
            const assets = new Map();
            for (const { p, t } of parts) {
                for (const a of t.assets) {
                    if (!assets.has(a.path)) assets.set(a.path, []);
                    assets.get(a.path).push(`${link(p)} (${a.replace ? 'replace' : `${a.edits.length} edit${a.edits.length === 1 ? '' : 's'}`}, ${p.status})`);
                }
            }
            out.push('| Asset | Patches |', '|---|---|');
            for (const name of [...assets.keys()].sort()) out.push(`| ${code(name)} | ${assets.get(name).join('<br>')} |`);
        }
        out.push('');
    }
    return out.join('\n');
}

// Returns true if the file changed.
function writeIndex() {
    const text = renderIndex();
    const old = fs.existsSync(INDEX_FILE) ? fs.readFileSync(INDEX_FILE, 'utf8') : null;
    if (old === text) return false;
    fs.writeFileSync(INDEX_FILE, text);
    return true;
}

module.exports = { INDEX_FILE, renderIndex, writeIndex };
